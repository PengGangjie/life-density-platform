  var lang = "zh";
  var listeners = [];

  function detect() {
    try {
      var q = String((window.location && window.location.search) || "");
      var m = q.match(/[?&]lang=(zh|en)\b/);
      if (m) return m[1];
    } catch (e) { /* 无 location 环境 */ }
    try {
      var saved = window.localStorage.getItem(KEY);
      if (saved === "zh" || saved === "en") return saved;
    } catch (e) { /* 存储不可用 */ }
    try {
      var nav = window.navigator && window.navigator.language || "";
      return /^zh/i.test(nav) ? "zh" : "en";
    } catch (e) { return "zh"; }
  }

  function t(key) {
    var v = (DICT[lang] || {})[key];
    if (v != null) return v;
    v = DICT.zh[key];
    if (v != null) return v;
    return key;
  }

  function apply() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    sweep();
  }

  /* 031 运行时清扫层：JS 模板渲染出的中文（词典反向映射 + 少量正则规则）。
     仅英文态执行；切回中文走整页 reload，避免半中半英。 */
  var sweepTimer = null;
  function sweep() {
    if (lang !== "en") return;
    var map = {};
    Object.keys(DICT.zh).forEach(function (k) {
      var zh = DICT.zh[k], en = DICT.en[k];
      if (zh && en && /[\u4e00-\u9fff]/.test(zh) && map[zh] === undefined) map[zh] = en;
    });
    var wd = { "星期日": "Sun", "星期一": "Mon", "星期二": "Tue", "星期三": "Wed", "星期四": "Thu", "星期五": "Fri", "星期六": "Sat" };
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (n) {
      var t = n.textContent;
      if (!t || !/[\u4e00-\u9fff]/.test(t)) return;
      var tr = map[t.trim()] !== undefined ? map[t.trim()] : map[t];
      if (tr !== undefined && tr !== t) { n.textContent = tr; return; }
      var nt = t
        .replace(/人生愿望 (\d+)/g, "Wish $1")
        .replace(/(\d{4})年(\d{1,2})月(\d{1,2})日\s*(星期[一二三四五六日])?/g, function (_, y, mo, d, w) {
          return y + "-" + mo + "-" + d + (w ? " " + (wd[w] || "") : "");
        });
      if (nt !== t) n.textContent = nt;
    });
  }
  function scheduleSweep() {
    if (sweepTimer) clearTimeout(sweepTimer);
    sweepTimer = setTimeout(sweep, 250);
  }

  function setLang(next, opts) {
    if (next !== "zh" && next !== "en") return lang;
    var changed = next !== lang;
    lang = next;
    if (!(opts && opts.noPersist)) {
      try { window.localStorage.setItem(KEY, next); } catch (e) { /* 忽略 */ }
    }
    if (changed || (opts && opts.force)) {
      apply();
      listeners.forEach(function (fn) { try { fn(lang); } catch (e) { /* 单个监听异常不阻断 */ } });
    }
    return lang;
  }

  function onChange(fn) { if (typeof fn === "function") listeners.push(fn); }

  lang = detect();
  /* 启动只落内存不写存储：localStorage 已是它本身，URL 参数=一次性预览不覆盖用户选择 */
  setLang(lang, { noPersist: true, force: true });

  /* 导航语言切换按钮：显示目标语言（中文态显示 EN） */
  function syncLangBtn() {
    var btn = document.getElementById("navLang");
    if (btn) btn.textContent = lang === "zh" ? "EN" : "中";
  }
  function bindLangBtn() {
    var btn = document.getElementById("navLang");
    if (!btn) return;
    btn.addEventListener("click", function () {
      var next = lang === "zh" ? "en" : "zh";
      setLang(next);
      syncLangBtn();
      if (next === "zh") { try { localStorage.setItem(KEY, "zh"); } catch (e) {} location.reload(); }
      else { scheduleSweep(); setTimeout(scheduleSweep, 900); setTimeout(scheduleSweep, 2200); }
    });
    syncLangBtn();
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", bindLangBtn);
  } else {
    bindLangBtn();
  }

  /* 031：MutationObserver + 确定性延时补扫——lixing-v1 等脚本在
     DOMContentLoaded 前同步渲染（observer 接不到），必须靠 load 后分层补扫兜住。 */
  if (typeof MutationObserver !== "undefined") {
    var mo = new MutationObserver(function () { scheduleSweep(); });
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", function () {
        mo.observe(document.body, { childList: true, subtree: true, characterData: true });
        scheduleSweep();
      });
    } else {
      mo.observe(document.body, { childList: true, subtree: true, characterData: true });
      scheduleSweep();
    }
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () { scheduleSweep(); });
  } else {
    scheduleSweep();
  }
  if (typeof window !== "undefined") {
    window.addEventListener("load", function () {
      scheduleSweep();
      [400, 1200, 2600, 4200].forEach(function (ms) { setTimeout(scheduleSweep, ms); });
    });
  }

  window.LixingI18n = {
    t: t,
    lang: function () { return lang; },
    setLang: setLang,
    apply: apply,
    onChange: onChange,
    _dict: DICT
  };
